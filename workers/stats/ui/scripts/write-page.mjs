// After `vite build`: checks dist/index.html is self-contained and writes it into the Worker as src/page.generated.ts.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const html = readFileSync(path.resolve(here, '../dist/index.html'), 'utf8')
const problems = []
if (/<script[^>]*\ssrc=/i.test(html)) problems.push('a <script src>')
if (/<link[^>]*rel=["']?(stylesheet|preload|modulepreload)/i.test(html)) problems.push('a linked stylesheet or preload')
if (/(?:src|href)=["']?https?:/i.test(html)) problems.push('a src/href to another origin')
if (/url\(\s*["']?https?:/i.test(html)) problems.push('a remote url()')
if (/@import\s+(?:url\()?["']?https?:/i.test(html)) problems.push('a remote @import')
if (!html.includes('<title>Everybird stats</title>')) problems.push('the title')
if (problems.length) { console.error('write-page: dist/index.html is not self-contained: ' + problems.join(', ')); process.exit(1) }
const out = path.resolve(here, '../../src/page.generated.ts')
writeFileSync(out, '// GENERATED by workers/stats/ui (scripts/write-page.mjs). Do not edit by hand.\n// Regenerate: npm --prefix workers/stats/ui run build (wrangler deploy runs it too).\n// The private dashboard page: one self-contained HTML file (scripts, styles and fonts inlined).\nexport const PAGE: string = ' + JSON.stringify(html) + '\n')
console.log('write-page: ' + path.relative(process.cwd(), out) + ' (' + (html.length / 1024).toFixed(1) + ' KiB of HTML)')
