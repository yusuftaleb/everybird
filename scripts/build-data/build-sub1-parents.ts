// Writes src/lib/import/sub1-parents.ts: for the countries whose regions.v1.json holds two ISO 3166-2 tiers, each
// lower-tier code -> its top-level ancestor (eBird's subnational1). observation.org writes the lower tier (Belgian
// provinces, French departments, Spanish and Italian provinces, English counties); the import rolls them up.
// Run: DATA_RAW=<data/raw> npx tsx scripts/build-data/build-sub1-parents.ts (reads iso_3166-2.json from iso-codes).
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import type { Regions } from '../../src/lib/species/types'

const ROLLUP_COUNTRIES = ['BE', 'FR', 'ES', 'IT', 'GB'] as const

type IsoSub = { code: string; name: string; parent?: string }

/**
 * Codes regions.v1.json keeps that the current ISO 3166-2 list no longer has (older editions, which Natural Earth
 * still uses), with their top-level region. French overseas codes (FR-GF, FR-GP, FR-MQ, FR-RE, FR-YT) are top-level
 * themselves and stay out.
 */
const MANUAL_PARENTS: Readonly<Record<string, string>> = {
  'FR-75': 'FR-IDF', // Paris, now FR-75C
  'IT-AO': 'IT-23', // Aosta, now the region itself
  // Sardinia's provinces before 2016.
  'IT-CI': 'IT-88', 'IT-OG': 'IT-88', 'IT-OT': 'IT-88', 'IT-VS': 'IT-88',
  // Northern Ireland's districts before 2015.
  'GB-ANT': 'GB-NIR', 'GB-ARD': 'GB-NIR', 'GB-ARM': 'GB-NIR', 'GB-BLA': 'GB-NIR', 'GB-BLY': 'GB-NIR',
  'GB-BNB': 'GB-NIR', 'GB-CGV': 'GB-NIR', 'GB-CKF': 'GB-NIR', 'GB-CKT': 'GB-NIR', 'GB-CLR': 'GB-NIR',
  'GB-CSR': 'GB-NIR', 'GB-DGN': 'GB-NIR', 'GB-DOW': 'GB-NIR', 'GB-DRY': 'GB-NIR', 'GB-FER': 'GB-NIR',
  'GB-LMV': 'GB-NIR', 'GB-LRN': 'GB-NIR', 'GB-LSB': 'GB-NIR', 'GB-MFT': 'GB-NIR', 'GB-MYL': 'GB-NIR',
  'GB-NDN': 'GB-NIR', 'GB-NTA': 'GB-NIR', 'GB-NYM': 'GB-NIR', 'GB-OMH': 'GB-NIR', 'GB-STB': 'GB-NIR',
  // English unitary authorities and a county since replaced.
  'GB-BMH': 'GB-ENG', 'GB-POL': 'GB-ENG', 'GB-NTH': 'GB-ENG',
}

/** Child -> top-level ancestor, walking the ISO parent chain (FR-67 -> FR-6AE -> FR-GES); only codes in `sub1`. */
export function sub1Parents(iso: IsoSub[], sub1: Regions['sub1']): Record<string, string> {
  const parentOf = new Map<string, string>()
  for (const e of iso) {
    if (!e.parent) continue
    const country = e.code.split('-')[0]
    // iso-codes writes full codes; an older edition wrote the bare suffix ("VLG").
    parentOf.set(e.code, e.parent.includes('-') ? e.parent : `${country}-${e.parent}`)
  }
  for (const [code, parent] of Object.entries(MANUAL_PARENTS)) parentOf.set(code, parent)
  const out: Record<string, string> = {}
  for (const code of Object.keys(sub1)) {
    const country = code.split('-')[0]
    if (!(ROLLUP_COUNTRIES as readonly string[]).includes(country)) continue
    let top = code
    for (let hops = 0; parentOf.has(top) && hops < 5; hops++) top = parentOf.get(top)!
    if (top === code) continue
    if (!sub1[top] || parentOf.has(top)) throw new Error(`${code}: top-level ancestor ${top} is not a regions.v1.json top-level code`)
    out[code] = top
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => (a < b ? -1 : 1)))
}

function main() {
  const raw = process.env.DATA_RAW ?? 'data/raw'
  const iso: IsoSub[] = JSON.parse(readFileSync(resolve(raw, 'iso_3166-2.json'), 'utf8'))['3166-2']
  const regions: Regions = JSON.parse(readFileSync('public/data/regions.v1.json', 'utf8'))
  const parents = sub1Parents(iso, regions.sub1)
  const lines = Object.entries(parents).map(([k, v]) => `  '${k}': '${v}',`)
  const body = [
    '// Generated by scripts/build-data/build-sub1-parents.ts from iso-codes (iso_3166-2.json) and regions.v1.json.',
    '// Do not edit. Rerun: DATA_RAW=<data/raw> npx tsx scripts/build-data/build-sub1-parents.ts',
    '',
    `/** Lower-tier ISO 3166-2 code -> its top-level region (eBird's subnational1), for ${ROLLUP_COUNTRIES.join(', ')}. */`,
    'export const SUB1_PARENT: Readonly<Record<string, string>> = {',
    ...lines,
    '}',
    '',
  ].join('\n')
  writeFileSync('src/lib/import/sub1-parents.ts', body)
  console.log(`sub1-parents: ${lines.length} codes`)
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main()
