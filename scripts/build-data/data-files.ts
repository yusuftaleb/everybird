// The data files the app fetches, published under content-hashed names so they can be cached for a year.
//
// Writes public/data/masks.v2.json (every order's masks in one file: { <Order>: { code: [w, h, bits] } }, built from
// the per-order public/data/masks/<Order>.v1.json, which stay the source of truth for the build scripts and the link
// preview) and src/lib/data-files.ts (logical name -> hashed name, e.g. species.v1.json -> species.v1.3f9a2b1c4d.json).
// The app fetches `${NEXT_PUBLIC_DATA_BASE}/<hashed name>` (the R2 bucket, https://stickers.yusuftaleb.com/data) and
// falls back to /data/<logical name> on this deployment; scripts/deploy/upload-stickers-r2.ts uploads the hashed files.
//
// Run after anything that changes public/data (npm run data, build-sample-pack, the huashu sync does it itself):
//   npx tsx scripts/build-data/data-files.ts
// tests/data-files.test.ts fails when the committed outputs and public/data disagree.
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/** The files under public/data the client fetches, by their logical names. */
export const DATA_FILE_NAMES = [
  'species.v1.json', 'taxonomy.v1.json', 'regions.v1.json', 'masks.v2.json',
  'sample.v1.json', 'sample-pack.v1.json', 'inat-synonyms.v1.json',
] as const
export const MASKS_BUNDLE = 'public/data/masks.v2.json'
export const DATA_FILES_TS = 'src/lib/data-files.ts'

/** species.v1.json + its bytes -> species.v1.<first 10 hex of sha256>.json */
export function hashedName(name: string, content: string | Buffer): string {
  const h = createHash('sha256').update(content).digest('hex').slice(0, 10)
  return name.replace(/\.json$/, `.${h}.json`)
}

/** Every order's masks as one JSON text, orders and codes sorted. */
export function masksBundle(tables: Iterable<[string, Record<string, unknown>]>): string {
  const all = [...tables].sort(([a], [b]) => (a < b ? -1 : 1))
  return JSON.stringify(Object.fromEntries(all.map(([ord, rec]) => [ord, Object.fromEntries(Object.entries(rec).sort(([x], [y]) => (x < y ? -1 : 1)))])))
}

export function readOrderMasks(dir: string): Map<string, Record<string, unknown>> {
  const out = new Map<string, Record<string, unknown>>()
  for (const f of readdirSync(dir).filter((f) => f.endsWith('.v1.json')).sort()) out.set(f.replace(/\.v1\.json$/, ''), JSON.parse(readFileSync(join(dir, f), 'utf8')))
  return out
}

export function dataFilesTs(read: (name: string) => string): string {
  const rows = DATA_FILE_NAMES.map((n) => `  '${n}': '${hashedName(n, read(n))}',`)
  return [
    '// Generated by scripts/build-data/data-files.ts: do not edit. Logical data file -> its content-hashed name.',
    'export const DATA_FILES = {',
    ...rows,
    '} as const',
    'export type DataFile = keyof typeof DATA_FILES',
    '',
  ].join('\n')
}

/**
 * Both outputs (repo-relative path -> text). `read` gives a public/data file's text by name, so a caller with
 * unwritten changes (the huashu sync) can overlay them; `masks` are the per-order tables.
 */
export function buildDataFiles(read: (name: string) => string, masks: Iterable<[string, Record<string, unknown>]>): Map<string, string> {
  const bundle = masksBundle(masks)
  const ts = dataFilesTs((n) => (n === 'masks.v2.json' ? bundle : read(n)))
  return new Map([[MASKS_BUNDLE, bundle], [DATA_FILES_TS, ts]])
}

if (process.argv[1] && /data-files\.ts$/.test(process.argv[1])) {
  const root = process.cwd()
  const out = buildDataFiles((n) => readFileSync(join(root, 'public/data', n), 'utf8'), readOrderMasks(join(root, 'public/data/masks')))
  for (const [rel, text] of out) writeFileSync(join(root, rel), text)
  console.log(readFileSync(join(root, DATA_FILES_TS), 'utf8'))
}
