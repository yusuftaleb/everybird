/** Breeds in the northern hemisphere (IOC realms PAL / NA, or Arctic and Siberian text). */
export function breedsNorth(rec: RangeRecord): boolean {
  const realm = rec.range?.ioc?.breedingRegion ?? ''
  return /\b(PAL|NA)\b|Holarctic/.test(realm) || /^\s*breeds[^;]*(Arctic|Siberia|Eurasia|Europe|Canada|Alaska)/i.test(rec.range?.text ?? '')
}

/** Where in the zone the bird is in month `month` (1–12), or undefined: residents any month, migrants in their season. */
export function seenIn(rec: RangeRecord, zoneId: ZoneId, month: number): ZoneHit | undefined {
  const zone: Zone = ZONES[zoneId]
  if (zone.realm && !zone.realm.test(rec.range?.ioc?.breedingRegion ?? '') && !zone.realm.test(rec.range?.ioc?.nonbreeding ?? '')) return undefined
  // IOC's "widespread" for a bird of the Australasian realm alone: all of Australia (Pacific Black Duck, Grey Teal).
  if (zone.realm && rec.range?.ioc?.breedingRegion === 'AU' && /^\s*widespread\s*$/i.test(rec.range.ioc.breeding ?? '')) return { sub1: zone.sub1('', [], rec), breadth: 3, phrase: 'widespread' }
  const { breed, winter } = rangeStrings(rec)
  const migrant = rec.traits?.migration === 'migratory'
  const b = zoneMatch(zone, breed, rec)
  if (b && (!migrant || SUMMER[HEMI[zoneId]].includes(month))) return b
  const away = breedsNorth(rec) ? BOREAL_WINTER : AUSTRAL_WINTER
  if (away.includes(month)) return zoneMatch(zone, winter, rec)
  return undefined
}

/** How likely a birder is to meet it there: least concern and widespread birds first, garden birds before far migrants. */
export function commonness(rec: RangeRecord, hit: ZoneHit): number {
  const iucn = ({ LC: 1, NT: 0.35, VU: 0.12, EN: 0.05, CR: 0.02 } as Record<string, number>)[rec.conservation?.iucn ?? ''] ?? 0.8
  const garden = rec.traits?.habitat === 'Human Modified' ? 1.5 : 1
  const shy = rec.traits?.habitatDensity === 1 ? 0.85 : 1
  const farMigrant = rec.traits?.migration === 'migratory' && breedsNorth(rec) && !rec.range?.ioc?.breedingRegion?.includes('AU') ? 0.55 : 1
  const { breed, winter } = rangeStrings(rec)
  const spread = [...breed, ...winter].reduce((n, s) => n + rangeParts(s).parts.length, 0)
  return iucn * garden * shy * farMigrant * hit.breadth * (1 + 0.15 * Math.log1p(spread))
}

