function main() {
  const raw = resolve(process.cwd(), 'data/raw')
  const huashu = loadHuashu(resolve(raw, 'huashu')) as (HuashuRecord & RangeRecord)[]
  const taxa = loadEbirdTaxonomy(resolve(raw, 'ebird-taxonomy.json'))
  const overrides = JSON.parse(readFileSync(resolve('data/overrides.json'), 'utf8')) as Overrides
  const { matches } = matchHuashu(huashu, taxa, overrides)
  const species = (JSON.parse(readFileSync(resolve('public/data/species.v1.json'), 'utf8')) as SpeciesFile).species
  const regions = JSON.parse(readFileSync(resolve('public/data/regions.v1.json'), 'utf8')) as Regions
  const linkable = new Set(JSON.parse(readFileSync(resolve('data/link-index.json'), 'utf8')) as string[])
  const cands: Candidate[] = species
    // Only birds that keep their own range: a huashu record standing in for a split (Hooded Crow drawn from Carrion
    // Crow's record) carries the other species' range. And ashore: no seabirds.
    .filter((s: SpeciesRow) => {
      const h = matches.get(s.code) as (HuashuRecord & RangeRecord) | undefined
      return s.st && linkable.has(s.code) && !!h && (h.ids.ebird === s.code || h.scientificName === s.sci) && h.traits?.habitat !== 'Marine'
    })
    .map((s) => ({ code: s.code, com: s.com, ord: s.ord, to: s.to, rec: matches.get(s.code) as RangeRecord }))
  const missing = HOME_STARTERS.filter((n) => { const c = cands.find((x) => x.com === n); return !c || !seenIn(c.rec, HOME.zone, 3) })
  if (missing.length) console.warn(`starters left out (no sticker, no link code or no NSW range): ${missing.join(', ')}`)
  const out = generateSample(cands)
  for (const b of out.birds) {
    if (!regions.countries[b.place!.country!] || !regions.sub1[b.place!.sub1!]) throw new Error(`unknown region ${JSON.stringify(b.place)}`)
  }
  writeFileSync(resolve('public/data/sample.v1.json'), JSON.stringify(out))
  const by = new Map<string, number>()
  for (const b of out.birds) by.set(b.place!.country!, (by.get(b.place!.country!) ?? 0) + 1)
  const ords = new Set(out.birds.map((b) => species.find((s) => s.code === b.code)!.ord))
  const dates = out.birds.map((b) => b.date!).sort()
  console.log(`sample.v1.json: ${out.birds.length} species, ${by.size} countries (${[...by].map(([c, n]) => `${c} ${n}`).join(', ')}), ${ords.size} orders, ${dates[0]} to ${dates.at(-1)}, seed ${SEED}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main()
