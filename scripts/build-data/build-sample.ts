const DIR_WORDS = new Set([
  'n', 's', 'e', 'w', 'ne', 'nw', 'se', 'sw', 'c', 'nc', 'sc', 'ec', 'wc', 'north', 'south', 'east', 'west',
  'northeast', 'northwest', 'southeast', 'southwest',
  'northern', 'southern', 'eastern', 'western', 'central', 'northeastern', 'northwestern', 'southeastern', 'southwestern',
  'north-eastern', 'north-western', 'south-eastern', 'south-western', 'east-central', 'west-central', 'north-central', 'south-central',
])
/** Words that narrow a place without a direction ("inland Australia", "far n Australia"). */
const NARROW_WORDS = new Set(['far', 'extreme', 'coastal', 'inland', 'interior', 'arid', 'semiarid', 'tropical', 'montane', 'peninsular', 'mainland', 'lowland', 'lowlands'])
const LONG_DIR: Record<string, string> = {
  north: 'n', south: 's', east: 'e', west: 'w', northeast: 'ne', northwest: 'nw', southeast: 'se', southwest: 'sw',
  northern: 'n', southern: 's', eastern: 'e', western: 'w', central: 'c',
  northeastern: 'ne', northwestern: 'nw', southeastern: 'se', southwestern: 'sw', 'north-eastern': 'ne', 'north-western': 'nw',
  'south-eastern': 'se', 'south-western': 'sw', 'east-central': 'ec', 'west-central': 'wc', 'north-central': 'nc', 'south-central': 'sc',
}
/** Phrases that never mean a birder would meet the bird there. */
const NOT_THERE = /introduc|vagran|accidental|casual|formerly|extinct|extirpat|escape|feral|straggler|rarely|\brare\b|\bfew\b|sparse|scarce|irregular|perhaps|possibly|probably|unknown|uncertain|released|ranges|wanders|dispers|visitor|visits|stray/i

/**
 * The direction words just before `at` in `s` ("se Australia" -> ['se'], "n, e Australia" -> ['n', 'e']; bare -> []),
 * and whether a narrowing word ("inland", "far") stands there too.
 */
export function dirsBefore(s: string, at: number): { dirs: string[]; narrow: boolean } {
  const words = s.slice(0, at).split(/[\s,]+/).filter(Boolean).reverse()
  const dirs: string[] = []
  let narrow = false
  for (const raw of words) {
    const w = raw.toLowerCase().replace(/[()]/g, '').replace(/^(north|south|east|west)-?(central|eastern|western)$/, (_m, a: string, b: string) => `${a}-${b}`)
    if (w === 'and' || w === 'to' || w === 'of' || w === 'the') continue
    if (NARROW_WORDS.has(w)) { narrow = true; continue }
    if (!DIR_WORDS.has(w)) break
    dirs.push(LONG_DIR[w] ?? w)
  }
  return { dirs, narrow }
}

/** A description's clauses: split at ';' and at sentence ends, but never inside brackets ("(s of South I.; New Zealand)"). */
export function clauses(s: string): string[] {
  const out: string[] = []
  let depth = 0, cur = ''
  for (let i = 0; i < s.length; i++) {
    const ch = s[i]
    if (ch === '(') depth++
    if (ch === ')') depth = Math.max(0, depth - 1)
    const end = depth === 0 && (ch === ';' || (ch === '.' && /^\s+[A-Z]/.test(s.slice(i + 1, i + 3)) && !/\b(I|Is|Pen|Arch|Mts?|St)$/.test(cur)))
    if (end) {
      out.push(cur)
      cur = ''
    } else cur += ch
  }
  if (cur.trim()) out.push(cur)
  return out
}

/**
 * The phrases of a range string that place the bird somewhere: split at ';' and ',' (but not inside brackets), without
 * the "introduced", "vagrant" and similar clauses, and with "except …" asides cut out (their places are returned apart).
 */
export function rangeParts(s: string | undefined): { parts: string[]; except: string[] } {
  const parts: string[] = []
  const except: string[] = []
  if (!s) return { parts, except }
  for (const clause of clauses(s)) {
    if (NOT_THERE.test(clause)) continue
    const cut = clause.replace(/\(?\b(except|excluding|but not)\b([^);]*)\)?/gi, (_m, _w: string, inner: string) => {
      except.push(inner)
      return ''
    })
    let depth = 0, cur = ''
    for (const ch of cut) {
      if (ch === '(') depth++
      if (ch === ')') depth = Math.max(0, depth - 1)
      if (ch === ',' && depth === 0) {
        parts.push(cur.trim())
        cur = ''
      } else cur += ch
    }
    if (cur.trim()) parts.push(cur.trim())
  }
  return { parts: parts.filter(Boolean), except }
}

/** A text clause about the non-breeding season ("winters …", "nonbreeding …", "migrates to …"). */
const WINTER_CLAUSE = /^\s*(winters?|wintering|nonbreeding|non-breeding|migrates?|in winter|austral winter|boreal winter)/i

/** Breeding (or resident) range strings and non-breeding range strings of a record. */
export function rangeStrings(rec: RangeRecord): { breed: string[]; winter: string[] } {
  const breed: string[] = [], winter: string[] = []
  const text = rec.range?.text ?? ''
  for (const clause of clauses(text)) (WINTER_CLAUSE.test(clause) ? winter : breed).push(clause)
  if (rec.range?.ioc?.breeding) breed.push(rec.range.ioc.breeding)
  // IOC's nonbreeding field starts with the realms ("AF, OR, AU : …"): keep only the places.
  if (rec.range?.ioc?.nonbreeding) winter.push(rec.range.ioc.nonbreeding.replace(/^[^:]*:\s*/, ''))
  return { breed: breed.filter((x) => x.trim()), winter: winter.filter((x) => x.trim()) }
}

/** A place name to look for, and the direction words allowed in front of it (undefined: a specific place, any). */
export type NameRule = { re: RegExp; dirs?: string[] }
/** One place the birder visits: the country's names, what rules a phrase out, and a sub1 for a matching phrase. */
export type Zone = {
  country: string; names: NameRule[]; exclude?: RegExp; forbidExcept?: RegExp; realm?: RegExp
  /** A phrase must also match this (Kenya: the range carries on past it, not a list of northern neighbours). */
  require?: RegExp
  /** Directions that cover where the birder goes as well as the whole country does ("e Australia" from Sydney). */
  core?: string[]
  sub1: (phrase: string, dirs: string[], rec: RangeRecord) => string
}
/** Where the phrase put the bird, and how much of the zone it covers (3: all of the country … 1: a part of it). */
export type ZoneHit = { sub1: string; breadth: number; phrase: string }

/** The birder stays ashore: seas, offshore islets and pelagic ranges don't count. */
const AT_SEA = /\b(off|offshore|at sea|pelagic|oceans?|waters|seas)\b/i

/** Bracketed asides with their offsets ("Tasmania (se Australia)" -> one aside at 9). */
function asides(p: string): { text: string; at: number }[] {
  const out: { text: string; at: number }[] = []
  const re = /\(([^()]*)\)/g
  for (let m; (m = re.exec(p)); ) out.push({ text: m[1], at: m.index + 1 })
  return out
}

/**
 * The first phrase in `strings` that puts the bird in `zone`, or undefined. A name inside brackets counts only as a
 * specific place or a bare country ("Prince Edward, Macquarie (se of Australia)" and "Tasmania (se Australia)" are
 * glosses, not Australia).
 */
export function zoneMatch(zone: Zone, strings: string[], rec: RangeRecord): ZoneHit | undefined {
  // An "except" that leaves out the visited part, in any of the record's descriptions, rules the zone out.
  const all = rangeStrings(rec)
  if (zone.forbidExcept && [...all.breed, ...all.winter].some((s) => rangeParts(s).except.some((x) => zone.forbidExcept!.test(x)))) return undefined
  for (const s of strings) {
    const { parts } = rangeParts(s)
    for (const p of parts) {
      if (AT_SEA.test(p) || zone.exclude?.test(p) || (zone.require && !zone.require.test(p))) continue
      const outside = p.replace(/\([^()]*\)/g, (m) => ' '.repeat(m.length))
      for (const rule of zone.names) {
        const re = new RegExp(rule.re.source, rule.re.flags.includes('g') ? rule.re.flags : rule.re.flags + 'g')
        const tries: { s: string; inner: boolean }[] = [{ s: outside, inner: false }, ...asides(p).map((a) => ({ s: a.text, inner: true }))]
        for (const t of tries) for (const m of t.s.matchAll(re)) {
          const { dirs, narrow } = dirsBefore(t.s, m.index)
          if (rule.dirs) {
            if (t.inner && dirs.length) continue
            if (!(dirs.length === 0 ? rule.dirs.includes('') : dirs.some((d) => rule.dirs!.includes(d)))) continue
          }
          const core = zone.core && dirs.some((d) => zone.core!.includes(d))
          const breadth = (!rule.dirs ? 1 : dirs.length === 0 || core ? 3 : dirs.length >= 2 ? 2 : 1.4) * (narrow ? 0.5 : 1)
          return { sub1: zone.sub1(p, dirs, rec), breadth, phrase: p }
        }
      }
    }
  }
  return undefined
}

