/** mulberry32: a small seeded generator, the same numbers on every machine. */
export function rng(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** `n` items without replacement, each with chance growing with its weight (Efraimidis–Spirakis). */
function weightedPick<T>(items: T[], weight: (t: T) => number, n: number, r: () => number): T[] {
  return items
    .map((t) => ({ t, k: Math.log(r()) / Math.max(1e-9, weight(t)) }))
    .sort((a, b) => b.k - a.k)
    .slice(0, n)
    .map((x) => x.t)
}

function poisson(lambda: number, r: () => number): number {
  const l = Math.exp(-lambda)
  let k = 0, p = 1
  do { k++; p *= r() } while (p > l)
  return k - 1
}

const DOMESTIC = new Set<ZoneId>(['qld', 'tas'])
const homeBird = (rec: RangeRecord) => [1, 4, 7, 10].some((m) => seenIn(rec, HOME.zone, m))

const ym = (y: number, m: number) => `${y}-${String(m).padStart(2, '0')}`
function monthsBetween(from: string, to: string): string[] {
  const out: string[] = []
  let [y, m] = from.split('-').map(Number)
  const [ty, tm] = to.split('-').map(Number)
  while (y < ty || (y === ty && m <= tm)) {
    out.push(ym(y, m))
    if (++m > 12) { m = 1; y++ }
  }
  return out
}
/** NSW lifers by month of the year: spring migrants and summer shorebirds, quiet winters. */
const HOME_SEASON = [0, 1.1, 0.9, 0.8, 0.6, 0.45, 0.4, 0.5, 0.8, 1.5, 1.6, 1.4, 1.2]

/** The made-up birder's list: deterministic for a seed and the candidates. */
export function generateSample(cands: Candidate[], seed = SEED): SampleFile {
  const r = rng(seed)
  const used = new Set<string>()
  const orders = new Set<string>()
  const birds: SampleBird[] = []
  const tripMonths = new Set(TRIPS.flatMap((t) => t.months.map(([m]) => m)))
  type Event = { month: string; zone: ZoneId; n: number }
  const events: Event[] = TRIPS.flatMap((t) => {
    let left = t.lifers
    return t.months.map(([month, share], i) => {
      const n = i === t.months.length - 1 ? left : Math.round(t.lifers * share)
      left -= n
      return { month, zone: t.zone, n }
    })
  })
  // Home: a big first year, then fewer each year; spring and summer busier than winter; nothing while away.
  const homeMonths = monthsBetween(HOME.from, HOME.to).filter((m) => !tripMonths.has(m))
  const start = Number(HOME.from.slice(0, 4)) * 12 + Number(HOME.from.slice(5)) - 1
  const raw = homeMonths.map((m) => {
    const age = (Number(m.slice(0, 4)) * 12 + Number(m.slice(5)) - 1 - start) / 12
    return HOME_SEASON[Number(m.slice(5))] * (age < 1 ? 4.5 : 1.8 / (1 + age * 0.3))
  })
  const scale = HOME.lifers / raw.reduce((a, b) => a + b, 0)
  homeMonths.forEach((month, i) => events.push({ month, zone: HOME.zone, n: poisson(raw[i] * scale, r) }))
  events.sort((a, b) => (a.month < b.month ? -1 : a.month > b.month ? 1 : a.zone === HOME.zone ? 1 : -1))
  // The last month at home always has a lifer (the latest lifer the stats and share image show).
  const last = events.filter((e) => e.zone === HOME.zone).at(-1)
  if (last && last.n === 0) last.n = 1

  // The starters fill the first two months at home.
  const starters = HOME_STARTERS.map((name) => cands.find((c) => c.com === name)).filter((c): c is Candidate => !!c && !!seenIn(c.rec, HOME.zone, 3))
  const firstHome = events.filter((e) => e.zone === HOME.zone).slice(0, 2)
  firstHome.forEach((e, i) => {
    const take = i === 0 ? starters.splice(0, Math.ceil((starters.length * 2) / 3)) : starters.splice(0)
    for (const c of take) {
      used.add(c.code)
      orders.add(c.ord)
      birds.push({ code: c.code, date: e.month, place: { country: ZONES[HOME.zone].country, sub1: seenIn(c.rec, HOME.zone, 3)!.sub1 } })
    }
  })

  for (const e of events) {
    if (!e.n) continue
    const month = Number(e.month.slice(5))
    const pool: { c: Candidate; hit: ZoneHit }[] = []
    for (const c of cands) {
      if (used.has(c.code) || DENY[e.zone]?.[c.code]) continue
      const hit = seenIn(c.rec, e.zone, month)
      // A trip inside Australia is for birds that don't come to New South Wales.
      if (hit && !(DOMESTIC.has(e.zone) && homeBird(c.rec))) pool.push({ c, hit })
    }
    // Home draws favour common birds strongly (they come first); trips a little less, and a trip goes looking for the
    // groups the birder has never seen (turacos in Kenya, a kiwi in New Zealand).
    const power = e.zone === HOME.zone ? 4 : 2
    const newGroup = (c: Candidate) => (e.zone !== HOME.zone && !orders.has(c.ord) ? 4 : 1)
    for (const { c, hit } of weightedPick(pool, (x) => commonness(x.c.rec, x.hit) ** power * newGroup(x.c), e.n, r)) {
      used.add(c.code)
      orders.add(c.ord)
      birds.push({ code: c.code, date: e.month, place: { country: ZONES[e.zone].country, sub1: hit.sub1 } })
    }
  }
  // Newest first, as eBird's life list download (the app sorts as it needs).
  const order = new Map(cands.map((c) => [c.code, c.to]))
  birds.sort((a, b) => (a.date! < b.date! ? 1 : a.date! > b.date! ? -1 : order.get(a.code)! - order.get(b.code)!))
  return { v: 1, note: NOTE, birds }
}

