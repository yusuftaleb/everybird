// Writes src/lib/flag-urls.ts: one static import per country flag in flag-icons (MIT, the set yusuftaleb.com uses),
// the 4x3 SVGs of two-letter ISO 3166-1 codes only. Next serves each imported file from the app's own origin (hashed
// under /_next/static/media), so a flag drawn on a canvas never taints it. Rerun after updating flag-icons.
// Run: npx tsx scripts/build-data/build-flags.ts
import { readdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const dir = resolve(__dirname, '../../node_modules/flag-icons/flags/4x3')
const codes = readdirSync(dir).filter((f) => /^[a-z]{2}\.svg$/.test(f)).map((f) => f.slice(0, 2)).sort()
const out = [
  '// Generated by scripts/build-data/build-flags.ts from flag-icons (MIT, Panayiotis Lipiridis). Do not edit.',
  ...codes.map((c) => `import f_${c} from 'flag-icons/flags/4x3/${c}.svg'`),
  '',
  'type Src = string | { src: string }',
  `export const FLAG_URLS: Record<string, Src> = { ${codes.map((c) => `${c.toUpperCase()}: f_${c}`).join(', ')} }`,
  '',
].join('\n')
writeFileSync(resolve(__dirname, '../../src/lib/flag-urls.ts'), out)
console.log(`flag-urls: ${codes.length} flags`)
