/** One per stage: the drag image's element, its grab offset, and the drop target it lights. */
export type Drag = { el: HTMLDivElement | null; card: { x: number; y: number; width: number; height: number } | null; cardEl: HTMLElement | null; over: boolean }
export const newDrag = (): Drag => ({ el: null, card: null, cardEl: null, over: false })

export function dragTo(d: Drag, at: { x: number; y: number }, off: { x: number; y: number }) {
  const el = d.el
  if (el) el.style.transform = `translate(${at.x - off.x}px, ${at.y - off.y}px)`
  const c = d.card
  const over = !!c && at.x >= c.x && at.x <= c.x + c.width && at.y >= c.y && at.y <= c.y + c.height
  if (over !== d.over) {
    d.over = over
    d.cardEl?.toggleAttribute('data-over', over)
  }
}
function bindDrag(d: Drag, el: HTMLDivElement | null) {
  d.el = el
}
export function dragEnd(d: Drag) {
  d.cardEl?.removeAttribute('data-over')
  d.over = false
  d.card = null
}

