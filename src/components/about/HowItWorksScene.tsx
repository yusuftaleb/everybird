/** A sticker from the configured sticker site, faded in once decoded; the product's outline if it fails to load. */
export function Sticker({ code }: { code: string }) {
  const [failed, setFailed] = useState(false)
  if (failed) return <Outline />
  return (
    // suppressHydrationWarning: the head's STICKER_READY_SCRIPT may have marked it data-ld before hydration
    // eslint-disable-next-line @next/next/no-img-element
    <img src={demoStickerUrl(code)} alt="" draggable={false} decoding="async" className="ebd-st" ref={markLoaded} suppressHydrationWarning
      onLoad={(e) => { e.currentTarget.dataset.ld = '' }} onError={() => setFailed(true)} />
  )
}

/**
 * A number ticking from the old value to the new one (ease-out quart), as the product's Tally does
 * (src/components/collage/Tally.tsx). It jumps inside a snap, off screen or in a still. The text is written only when
 * the shown number changes, in a contained box.
 */
function Tick({ value, ms }: { value: number; ms: number }) {
  const el = useRef<HTMLSpanElement>(null)
  const from = useRef(value)
  useLayoutEffect(() => {
    const node = el.current
    if (!node) return
    const a = from.current
    from.current = value
    let shown = ''
    const show = (v: number) => {
      const t = n(v)
      if (t !== shown) { shown = t; node.textContent = t }
    }
    const instant = !!node.closest('[data-instant], [data-offscreen], [data-still]')
    if (a === value || instant) { show(value); return }
    let raf = 0
    const t0 = performance.now()
    const step = (t: number) => {
      const k = Math.min(1, Math.max(0, (t - t0) / ms))
      show(Math.round(a + (value - a) * (1 - Math.pow(1 - k, 4))))
      if (k < 1) raf = requestAnimationFrame(step)
    }
    show(a)
    raf = requestAnimationFrame(step)
    return () => { cancelAnimationFrame(raf); show(value) }
  }, [value, ms])
  return <span ref={el}>{n(value)}</span>
}

