function ShareImage({ format, box, show }: { format: Format; box: { w: number; h: number }; show: boolean }) {
  const L = SHARE[format]
  const k = Math.min(box.w / L.W, box.h / L.H)
  const w = L.W * k, h = L.H * k
  const M = 64 * k
  const K = L.count
  const ar = AR[LATEST.code] ?? 1
  const icon = L.latest.icon * k
  return (
    <div className="ebd-img" data-show={show || undefined} data-format={format} style={{ width: w, height: h, left: (box.w - w) / 2, top: (box.h - h) / 2 }}>
      {Object.entries(L.tiles).map(([code, [x, y, tw, th]]) => (
        <span key={code} className="ebd-img-bird" style={{ left: x * k, top: y * k, width: tw * k, height: th * k }}><Sticker code={code} /></span>
      ))}
      <span className="ebd-img-mid" style={{ left: K.cx * k, top: K.cy * k, gap: K.gap * k }}>
        <span className="ebd-img-num" style={{ fontSize: K.size * k }}>{TOTAL}</span>
        <span className="ebd-img-label" style={{ fontSize: Math.max(3, K.labelSize * k) }}>Species</span>
      </span>
      <span className="ebd-img-latest" style={{ left: M, top: L.latest.y * k, height: icon, gap: 20 * k }}>
        <span className="ebd-img-latest-icon" style={{ width: icon, height: icon }}>
          <span style={{ width: ar >= 1 ? '100%' : `${ar * 100}%`, height: ar >= 1 ? `${100 / ar}%` : '100%' }}><Sticker code={LATEST.code} /></span>
        </span>
        <span className="ebd-img-latest-text">
          <span className="ebd-img-latest-label" style={{ fontSize: L.latest.label * k * 1.5 }}>Latest lifer · {LATEST_DATE}</span>
          <span className="ebd-img-latest-name" style={{ fontSize: L.latest.name * k * 1.5 }}>{LATEST.name}</span>
        </span>
      </span>
      <span className="ebd-img-rule" style={{ left: M, right: M, top: L.rule * k }} />
      <span className="ebd-img-foot" style={{ left: M, top: L.footer * k, height: 30 * k * 1.25 }}>
        <span className="ebd-img-mark" style={{ fontSize: 30 * k * 1.25 }}>Everybird</span>
        <span className="ebd-img-line" style={{ fontSize: 20 * k * 1.25 }}>{FOOTER_LINE}</span>
      </span>
    </div>
  )
}

